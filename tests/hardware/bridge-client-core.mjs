import assert from 'node:assert/strict';
import {HardwareClient} from '../../src/hardware/bridge-client.js';
const updates=[],pending=[];
const client=new HardwareClient({onState:state=>updates.push(state)});
client.session='first';
client.request=async(path,payload)=>new Promise(resolve=>pending.push({payload,resolve}));
const arm=client.command('arm',{supported:true});
const stop=client.stop();
assert.equal(pending.length,2);
assert.equal(pending[1].payload.operation,'stop');
assert.equal(pending[1].payload.sequence,2);
pending[0].resolve({state:'armed'});await arm;
assert.equal(client.busy,true,'Stop still pending must block new movement');
await assert.rejects(client.command('move',{targets:{shoulder_pan:1}}),/Wait/);
pending[1].resolve({state:'holding'});await stop;
assert.equal(client.busy,false);
const old=client.command('arm',{supported:true});
const oldRejected=assert.rejects(old,/previous panel session/);
client.close();client.session='second';
const current=client.command('arm',{supported:true});
pending[2].resolve({state:'old-operator'});await oldRejected;
assert.equal(client.busy,true,'Old response must not clear new session busy state');
assert.equal(updates.some(x=>x.state==='old-operator'),false);
pending[3].resolve({state:'current-operator'});await current;
assert.equal(updates.at(-1).state,'current-operator');
assert.equal(client.busy,false);
client.close();
console.log('Priority Stop, mutation serialization and stale-session isolation passed.');

